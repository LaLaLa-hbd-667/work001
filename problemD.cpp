/*
set就是自带整理和查重功能的超级收纳盒
1. 自动去重：你往里面塞 100 个数字 1，它里面永远只有一个 1。
2. 自动排序：你无论以什么顺序塞数字，它内部都会默默按从小到大的顺序排好（底层是红黑树结构）。
3. 查找极快：如果你想问它“你这里面有没有数字 5？”，它瞬间就能告诉你答案（时间复杂度是 O(\log n)，比 vector 一个个找快得多）。
这就是为什么代码里用它来做 s.find(sum) 的快速查找，以及用 set<int> ans 来自动去重。

#include <set>

1. 定义与初始化
set<int> s;                  // 定义一个存 int 的空集合（默认从小到大排）
set<string> s2;              // 也可以存字符串
set<int, greater<int>> s3;   // 定义一个从大到小排的集合

2. 插入数据（增）
· s.insert(x); ：把 x 插入集合。如果 x 已存在，插入操作会被忽略（不会报错），返回值可以忽略。

3. 删除数据（删）
· s.erase(x); ：删除值为 x 的元素。如果存在就删掉，不存在就什么都不做。
· s.erase(it); ：删除迭代器 it 指向的那个元素。
· s.erase(first, last); ：删除区间 [first, last) 内的所有元素。
· s.clear(); ：清空整个集合。

4. 查找与判断（查）—— 刷题最常用
· s.find(x); ：查找值为 x 的元素。如果找到了，返回指向该元素的迭代器；如果没找到，返回 s.end()。 （你图里第28行就是这个用法）。
· s.count(x); ：统计 x 在集合中出现的次数。因为 set 元素唯一，所以返回值要么是 1（存在），要么是 0（不存在）。判断存在时 if(s.count(x)) 也是个非常常用的简写。
· s.empty(); ：判断集合是否为空。空返回 true，否则返回 false。
· s.size(); ：返回集合中元素的个数。

5. 迭代器与遍历
· s.begin(); ：返回指向第一个元素（最小的元素）的迭代器。
· s.end(); ：返回指向最后一个元素后一个位置的迭代器。
· s.rbegin(); / s.rend(); ：反向迭代器（倒序遍历用）。
· 遍历方式（推荐用范围 for 循环，最方便）：

// 方式一：C++11 范围 for 循环（推荐）
for (int x : s) {
    cout << x << " ";
}

// 方式二：传统迭代器
for (set<int>::iterator it = s.begin(); it != s.end(); ++it) {
    cout << *it << " "; // 注意用 * 解引用
}

6. 高级操作（因为自带排序才能用）

· s.lower_bound(x); ：返回第一个 大于等于 x 的元素的迭代器。
· s.upper_bound(x); ：返回第一个 大于 x 的元素的迭代器。

注意：
1. 千万不要用下标访问！ set 不支持 s[0] 或者 s[i] 这种写法，
   它没有下标。必须通过迭代器（*it）访问。
2. 不能直接修改元素！ 如果你写 *it = 100; 是会报错的。
   因为 set 靠内部排序维持秩序，你随便改值就乱套了。
   如果要改，必须先 erase 旧值，再 insert 新值。
3. 性能选择：set 的查找是 O(\log n)。如果你不需要排序，
   只需要极速去重和查找，请用 unordered_set，
   它的平均查找时间是 O(1)，比 set 还要快！

*/
#include <iostream>
#include <vector>
#include <set>

using namespace std;

int main() {
    int n;
    // 读入数字个数
    if (!(cin >> n)) return 0;

    vector<int> a(n);
    set<int> s; // 用于快速查找数字是否在原集合中
    
    for (int i = 0; i < n; ++i) {
        cin >> a[i];
        s.insert(a[i]); // 将所有数放入 set
    }

    set<int> ans; // 用于存储满足条件的数，set自动去重

    // 双重循环枚举所有两两组合
    for (int i = 0; i < n; ++i) {
        for (int j = i + 1; j < n; ++j) {
            int sum = a[i] + a[j];
            
            // 如果这两个数之和在集合 s 中存在
            if (s.find(sum) != s.end()) {
                ans.insert(sum); // 将满足条件的数加入答案集合
            }
            /*
            对于find()函数：
            1. 如果找到了：它返回指向那个元素的迭代器（也就是真实房间的钥匙）。
            2. 如果没找到：它无法返回一个“空”，
               所以 C++ 规定，如果找不到，就返回 end()（把你扔到走廊上）。
               end() 是一个特殊的迭代器，它指向集合的最后一个元素的下一个位置
               （也就是不存在的位置）。
            *//*  
            如果你觉得 s.find(x) != s.end() 太长、太绕了，
            C++ 里有个更直观的写法，效果完全一样：
            if (s.count(sum)) {
                ans.insert(sum);
            }
            s.count(sum) 会直接返回 sum 在集合里出现的次数。
            因为 set 自动去重，所以返回值要么是 1（存在），要么是 0（不存在）。
            直接放进 if 里，1 就是真，0 就是假，非常好懂！          
            */
            /*
            如果你觉得 s.find(x) != s.end() 太长、太绕了，
            C++ 里有个更直观的写法，效果完全一样：
                if (s.count(sum)) {
                    ans.insert(sum);
                }
            s.count(sum) 会直接返回 sum 在集合里出现的次数。
            因为 set 自动去重，所以返回值要么是 1（存在），要么是 0（不存在）。
            直接放进 if 里，1 就是真，0 就是假，非常好懂！
            平时刷题，你可以用 s.count() 来判断存在，用 s.find() 来获取位置，
            看你喜欢哪种顺手就用哪种。
            */

        }
    }

    // 最终 ans 集合里有多少个元素，就是答案
    cout << ans.size() << endl;

    return 0;
}